#!/usr/bin/env node
/**
 * build-tokens.mjs — closes #321
 *
 * Reads src/tokens.json and regenerates src/tokens.css.
 * Run via: node scripts/build-tokens.mjs
 *          or npm run build:tokens
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const tokensPath = resolve(__dirname, "../src/tokens.json");
const outputPath = resolve(__dirname, "../src/tokens.css");

const tokens = JSON.parse(readFileSync(tokensPath, "utf8"));

/** Convert camelCase to kebab-case */
function toKebab(str) {
  return str.replace(/([A-Z])/g, (m) => `-${m.toLowerCase()}`);
}

const lines = [];

lines.push("/* =============================================================");
lines.push("   Design Tokens — auto-generated by scripts/build-tokens.mjs");
lines.push("   DO NOT EDIT MANUALLY — edit src/tokens.json instead.");
lines.push("   ============================================================= */");
lines.push("");
lines.push(":root {");

// Write the primitive color scales once.
for (const [group, scale] of Object.entries(tokens.color)) {
  if (group === "$type" || group === "semantic") continue;
  for (const [step, token] of Object.entries(scale)) {
    lines.push(`  --color-${group}-${step}: ${token.$value.hex};`);
  }
}
lines.push("");

// ── Typography ──────────────────────────────────────────────────────────────
lines.push("  /* ── Typography scale ── */");
lines.push(`  --font-sans:  ${tokens.typography.fontFamily.sans};`);
lines.push(`  --font-mono:  ${tokens.typography.fontFamily.mono};`);
lines.push("");

const sizeComments = { xs: "12px", sm: "13px", base: "14px", md: "16px", lg: "18px", xl: "20px", "2xl": "24px", "3xl": "30px", "4xl": "36px" };
for (const [key, value] of Object.entries(tokens.typography.fontSize)) {
  const comment = sizeComments[key] ? `  /* ${sizeComments[key]} */` : "";
  lines.push(`  --text-${key}: ${value};${comment}`);
}
lines.push("");

for (const [key, value] of Object.entries(tokens.typography.lineHeight)) {
  lines.push(`  --leading-${key}: ${value};`);
}
lines.push("");

for (const [key, value] of Object.entries(tokens.typography.fontWeight)) {
  lines.push(`  --font-${key}: ${value};`);
}
lines.push("");

// ── Spacing ─────────────────────────────────────────────────────────────────
lines.push("  /* ── Spacing scale (4px base grid) ── */");
for (const [key, value] of Object.entries(tokens.spacing)) {
  lines.push(`  --space-${key}: ${value};`);
}
lines.push("");

// ── Border radius ────────────────────────────────────────────────────────────
lines.push("  /* ── Border radius ── */");
for (const [key, value] of Object.entries(tokens.borderRadius)) {
  const name = key === "base" ? "--radius" : `--radius-${key}`;
  lines.push(`  ${name}: ${value};`);
}
lines.push("");

// ── Shadows ──────────────────────────────────────────────────────────────────
lines.push("  /* ── Shadows ── */");
for (const [key, value] of Object.entries(tokens.shadow)) {
  const name = key === "base" ? "--shadow" : `--shadow-${key}`;
  lines.push(`  ${name}: ${value};`);
}
lines.push("");

// ── Elevation ────────────────────────────────────────────────────────────────
lines.push("  /* ── Elevation (box-shadow scale) — closes #321 ── */");
for (const [key, value] of Object.entries(tokens.elevation)) {
  lines.push(`  --elevation-${key}: ${value};`);
}
lines.push("");

// ── Transitions ──────────────────────────────────────────────────────────────
lines.push("  /* ── Transitions ── */");
for (const [key, value] of Object.entries(tokens.transition)) {
  lines.push(`  --transition-${toKebab(key)}: ${value};`);
}

lines.push("}");
lines.push("");
const aliases = {
  bg: "background-primary",
  surface: "background-surface",
  border: "border-default",
  text: "text-primary",
  muted: "text-muted",
  focus: "border-focus",
  primary: "action-primary",
  "primary-dark": "action-hover",
  complete: "status-success",
  revoke: "status-error",
  brand: "action-primary",
  "brand-hover": "action-hover",
};

function writeTheme(selector, name, indent = "") {
  const theme = tokens.color.semantic[name];
  lines.push(`${indent}${selector} {`);
  lines.push(`${indent}  color-scheme: ${name === "light" ? "light" : "dark"};`);
  for (const [group, slots] of Object.entries(theme)) {
    for (const [slot, token] of Object.entries(slots)) {
      lines.push(`${indent}  --color-${group}-${toKebab(slot)}: ${token.$value.hex};`);
    }
  }
  for (const [alias, target] of Object.entries(aliases)) {
    lines.push(`${indent}  --color-${alias}: var(--color-${target});`);
  }
  if (name === "highContrast") {
    for (const [token, width] of Object.entries({ "shadow-sm": 1, shadow: 2, "shadow-lg": 3, "elevation-1": 1, "elevation-2": 2, "elevation-3": 3, "elevation-4": 4 })) {
      lines.push(`${indent}  --${token}: 0 0 0 ${width}px var(--color-border-default);`);
    }
  }
  lines.push(`${indent}}`, "");
}

writeTheme(':root, [data-theme="light"]', "light");
const system = ':root:where(:not([data-theme]), [data-theme="system"])';
lines.push("@media (prefers-color-scheme: dark) {");
writeTheme(system, "dark", "  ");
lines.push("}", "");
writeTheme('[data-theme="dark"], :root.theme-dark', "dark");
writeTheme(':root.theme-light', "light");
lines.push("@media (prefers-contrast: more) {");
writeTheme(system, "highContrast", "  ");
lines.push("}", "");
writeTheme('[data-theme="high-contrast"]', "highContrast");

writeFileSync(outputPath, lines.join("\n"), "utf8");
console.log("✓  Generated src/tokens.css");
